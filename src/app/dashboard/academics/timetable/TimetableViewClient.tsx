"use client";

import { useState, useTransition, useMemo } from "react";
import { useRouter } from "next/navigation";
import {
  Calendar,
  Clock,
  Settings,
  Users,
  Printer,
  Plus,
  Trash2,
  CheckCircle2,
  AlertCircle,
  AlertTriangle,
  Building,
  Check,
  X,
  FileText,
  Sparkles,
  BookOpen,
  ChevronDown,
  Layers,
  Wrench,
  GraduationCap,
  Download,
} from "lucide-react";
import {
  School,
  AcademicYear,
  ClassStream,
  SchoolClass,
  Subject,
  UserProfile,
  TimetableProfile,
  TimetablePeriod,
  TeacherAvailability,
  TimetableSlot,
} from "@/types/database";
import {
  createOrUpdateTimetableProfileAction,
  deleteTimetableProfileAction,
  autoGenerateDefaultPeriodsAction,
  saveTeacherAvailabilityAction,
  assignTimetableSlotAction,
  deleteTimetableSlotAction,
} from "@/app/academics/actions";

interface TimetableViewClientProps {
  school: School | null;
  academicYear: AcademicYear | null;
  isAdmin: boolean;
  isHod: boolean;
  isTeacher: boolean;
  currentUserId: string;
  initialProfiles: TimetableProfile[];
  classesWithStreams: (SchoolClass & { streams: ClassStream[] })[];
  allStreams: ClassStream[];
  subjects: Subject[];
  teachers: UserProfile[];
  initialAvailabilities: TeacherAvailability[];
  initialSlots: TimetableSlot[];
  initialStreamId: string;
  initialProfileId: string;
  initialTab: string;
}

const DAYS_OF_WEEK = [
  { day: 1, name: "Monday", shortName: "Mon", fr: "Lundi" },
  { day: 2, name: "Tuesday", shortName: "Tue", fr: "Mardi" },
  { day: 3, name: "Wednesday", shortName: "Wed", fr: "Mercredi" },
  { day: 4, name: "Thursday", shortName: "Thu", fr: "Jeudi" },
  { day: 5, name: "Friday", shortName: "Fri", fr: "Vendredi" },
];

export function TimetableViewClient({
  school,
  academicYear,
  isAdmin,
  isHod,
  isTeacher,
  currentUserId,
  initialProfiles,
  allStreams,
  subjects,
  teachers,
  initialAvailabilities,
  initialSlots,
  initialStreamId,
  initialProfileId,
  initialTab,
}: TimetableViewClientProps) {
  const router = useRouter();
  const [activeTab, setActiveTab] = useState<"grid" | "profiles" | "teachers" | "print">(
    (initialTab as any) || "grid"
  );
  const [selectedStreamId, setSelectedStreamId] = useState<string>(initialStreamId || allStreams[0]?.id || "");
  const [selectedProfileId, setSelectedProfileId] = useState<string>(initialProfileId || initialProfiles[0]?.id || "");
  const [selectedTeacherId, setSelectedTeacherId] = useState<string>(
    isTeacher && currentUserId ? currentUserId : teachers[0]?.id || ""
  );

  const [message, setMessage] = useState<{ type: "success" | "error"; text: string } | null>(null);
  const [isPending, startTransition] = useTransition();

  // Slot Assignment Modal State
  const [activeSlotModal, setActiveSlotModal] = useState<{
    dayOfWeek: number;
    period: TimetablePeriod;
    existingSlot?: TimetableSlot;
  } | null>(null);

  const [slotSubjectId, setSlotSubjectId] = useState<string>("");
  const [slotTeacherId, setSlotTeacherId] = useState<string>("");
  const [slotRoomName, setSlotRoomName] = useState<string>("");

  // New Profile Form State
  const [showProfileModal, setShowProfileModal] = useState(false);
  const [profileName, setProfileName] = useState("");
  const [profileSubsystem, setProfileSubsystem] = useState<"grammar" | "technical" | "commercial" | "general">("grammar");
  const [profileDuration, setProfileDuration] = useState(50);
  const [profileStartTime, setProfileStartTime] = useState("07:30");

  // Auto-generate Bell Periods State
  const [showAutoPeriodsModal, setShowAutoPeriodsModal] = useState(false);
  const [autoStart, setAutoStart] = useState("07:30");
  const [autoDuration, setAutoDuration] = useState(50);
  const [autoCount, setAutoCount] = useState(8);
  const [autoShortBreakPeriod, setAutoShortBreakPeriod] = useState(3);
  const [autoShortBreakDuration, setAutoShortBreakDuration] = useState(20);
  const [autoLunchPeriod, setAutoLunchPeriod] = useState(5);
  const [autoLunchDuration, setAutoLunchDuration] = useState(40);

  // Selected stream details
  const activeStream = useMemo(() => {
    return allStreams.find((s) => s.id === selectedStreamId) || allStreams[0] || null;
  }, [allStreams, selectedStreamId]);

  // Selected profile details with its periods
  const activeProfile = useMemo(() => {
    const found = initialProfiles.find((p) => p.id === selectedProfileId);
    return found || initialProfiles[0] || null;
  }, [initialProfiles, selectedProfileId]);

  // Periods belonging to the active profile sorted by period number
  const activePeriods = useMemo(() => {
    if (!activeProfile?.periods) return [];
    return [...activeProfile.periods].sort((a, b) => a.period_number - b.period_number);
  }, [activeProfile]);

  // Map of slots for the selected stream: key = `${dayOfWeek}-${periodId}`
  const streamSlotsMap = useMemo(() => {
    const map = new Map<string, TimetableSlot>();
    for (const slot of initialSlots) {
      if (slot.class_stream_id === selectedStreamId) {
        map.set(`${slot.day_of_week}-${slot.period_id}`, slot);
      }
    }
    return map;
  }, [initialSlots, selectedStreamId]);

  // Teacher availability map for selected teacher: key = dayOfWeek
  const teacherAvailMap = useMemo(() => {
    const map = new Map<number, TeacherAvailability>();
    for (const av of initialAvailabilities) {
      if (av.teacher_id === selectedTeacherId) {
        map.set(av.day_of_week, av);
      }
    }
    return map;
  }, [initialAvailabilities, selectedTeacherId]);

  // ── Open Slot Assignment Modal ──
  const handleOpenSlotModal = (dayOfWeek: number, period: TimetablePeriod) => {
    if (period.is_break || (!isAdmin && !isHod)) return;

    const existing = streamSlotsMap.get(`${dayOfWeek}-${period.id}`);
    setActiveSlotModal({ dayOfWeek, period, existingSlot: existing });
    setSlotSubjectId(existing?.subject_id || subjects[0]?.id || "");
    setSlotTeacherId(existing?.teacher_id || "");
    setSlotRoomName(existing?.room_name || "");
    setMessage(null);
  };

  // ── Save Slot Assignment ──
  const handleSaveSlot = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!activeSlotModal || !activeStream || !activeProfile || !academicYear) return;

    setMessage(null);
    startTransition(async () => {
      const res = await assignTimetableSlotAction({
        academicYearId: academicYear.id,
        profileId: activeProfile.id,
        classStreamId: activeStream.id,
        dayOfWeek: activeSlotModal.dayOfWeek,
        periodId: activeSlotModal.period.id,
        subjectId: slotSubjectId,
        teacherId: slotTeacherId || null,
        roomName: slotRoomName || null,
        slotIdToIgnore: activeSlotModal.existingSlot?.id,
      });

      if (res?.error) {
        setMessage({ type: "error", text: res.error });
      } else {
        setMessage({ type: "success", text: "Timetable slot scheduled successfully." });
        setActiveSlotModal(null);
        router.refresh();
      }
    });
  };

  // ── Delete Slot ──
  const handleDeleteSlot = async (slotId: string) => {
    if (!confirm("Are you sure you want to clear this scheduled slot?")) return;
    setMessage(null);
    startTransition(async () => {
      const fd = new FormData();
      fd.set("slotId", slotId);
      const res = await deleteTimetableSlotAction(fd);
      if (res?.error) {
        setMessage({ type: "error", text: res.error });
      } else {
        setMessage({ type: "success", text: "Slot removed from timetable." });
        setActiveSlotModal(null);
        router.refresh();
      }
    });
  };

  // ── Create Timetable Profile ──
  const handleCreateProfile = async (e: React.FormEvent) => {
    e.preventDefault();
    setMessage(null);
    startTransition(async () => {
      const fd = new FormData();
      fd.set("name", profileName);
      fd.set("subsystem", profileSubsystem);
      fd.set("defaultPeriodDurationMinutes", String(profileDuration));
      fd.set("dayStartTime", profileStartTime);

      const res = await createOrUpdateTimetableProfileAction(fd);
      if (res?.error) {
        setMessage({ type: "error", text: res.error });
      } else {
        setMessage({ type: "success", text: `Timetable profile "${profileName}" created.` });
        setShowProfileModal(false);
        setProfileName("");
        router.refresh();
      }
    });
  };

  // ── Auto-generate Bell Schedule ──
  const handleAutoGeneratePeriods = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!activeProfile) return;
    setMessage(null);
    startTransition(async () => {
      const res = await autoGenerateDefaultPeriodsAction({
        profileId: activeProfile.id,
        dayStartTime: autoStart,
        periodDurationMinutes: Number(autoDuration),
        numberOfPeriods: Number(autoCount),
        shortBreakAfterPeriod: Number(autoShortBreakPeriod),
        shortBreakDuration: Number(autoShortBreakDuration),
        lunchBreakAfterPeriod: Number(autoLunchPeriod),
        lunchBreakDuration: Number(autoLunchDuration),
      });

      if (res?.error) {
        setMessage({ type: "error", text: res.error });
      } else {
        setMessage({ type: "success", text: "Standard bell schedule generated successfully." });
        setShowAutoPeriodsModal(false);
        router.refresh();
      }
    });
  };

  // ── Save Teacher Off-Days / Availability ──
  const handleToggleTeacherDay = async (dayOfWeek: number, currentAvailable: boolean) => {
    if (!selectedTeacherId) return;
    setMessage(null);
    startTransition(async () => {
      const updated = DAYS_OF_WEEK.map((d) => {
        const existing = teacherAvailMap.get(d.day);
        const isAvail = d.day === dayOfWeek ? !currentAvailable : existing?.is_available ?? true;
        return {
          dayOfWeek: d.day,
          startTime: existing?.start_time || "07:30:00",
          endTime: existing?.end_time || "15:30:00",
          isAvailable: isAvail,
          notes: existing?.notes || undefined,
        };
      });

      const res = await saveTeacherAvailabilityAction({
        teacherId: selectedTeacherId,
        availabilities: updated,
      });

      if (res?.error) {
        setMessage({ type: "error", text: res.error });
      } else {
        setMessage({ type: "success", text: "Teacher availability updated." });
        router.refresh();
      }
    });
  };

  return (
    <div className="space-y-6">
      {/* ── Top Level Subsystem & Tab Navigation Bar ── */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 border-b border-[#E8DFC9] pb-3">
        {/* Navigation Tabs */}
        <div className="flex items-center gap-1.5 bg-[#F5EFE0]/60 p-1 rounded-[6px] border border-[#E8DFC9] text-xs">
          <button
            type="button"
            onClick={() => setActiveTab("grid")}
            className={`px-3 py-1.5 rounded-[4px] font-semibold flex items-center gap-1.5 transition-colors cursor-pointer ${
              activeTab === "grid"
                ? "bg-white text-[#142010] shadow-2xs font-bold"
                : "text-[#525E4B] hover:text-[#142010]"
            }`}
          >
            <Calendar className="w-3.5 h-3.5 text-[#2A7C13]" />
            <span>Class Timetable</span>
          </button>

          {(isAdmin || isHod) && (
            <button
              type="button"
              onClick={() => setActiveTab("profiles")}
              className={`px-3 py-1.5 rounded-[4px] font-semibold flex items-center gap-1.5 transition-colors cursor-pointer ${
                activeTab === "profiles"
                  ? "bg-white text-[#142010] shadow-2xs font-bold"
                  : "text-[#525E4B] hover:text-[#142010]"
              }`}
            >
              <Clock className="w-3.5 h-3.5 text-[#B45309]" />
              <span>Bell Schedules &amp; Subsystems</span>
            </button>
          )}

          {(isAdmin || isHod) && (
            <button
              type="button"
              onClick={() => setActiveTab("teachers")}
              className={`px-3 py-1.5 rounded-[4px] font-semibold flex items-center gap-1.5 transition-colors cursor-pointer ${
                activeTab === "teachers"
                  ? "bg-white text-[#142010] shadow-2xs font-bold"
                  : "text-[#525E4B] hover:text-[#142010]"
              }`}
            >
              <Users className="w-3.5 h-3.5 text-[#2563EB]" />
              <span>Teacher Free Days</span>
            </button>
          )}

          <button
            type="button"
            onClick={() => setActiveTab("print")}
            className={`px-3 py-1.5 rounded-[4px] font-semibold flex items-center gap-1.5 transition-colors cursor-pointer ${
              activeTab === "print"
                ? "bg-white text-[#142010] shadow-2xs font-bold"
                : "text-[#525E4B] hover:text-[#142010]"
            }`}
          >
            <Printer className="w-3.5 h-3.5 text-[#6366F1]" />
            <span>Print Timetable Pack</span>
          </button>
        </div>

        {/* Action Controls for Active Tab */}
        {activeTab === "grid" && (
          <div className="flex items-center gap-2">
            <span className="text-[11px] font-semibold text-[#525E4B]">Class Group:</span>
            <select
              value={selectedStreamId}
              onChange={(e) => setSelectedStreamId(e.target.value)}
              className="px-2.5 py-1 text-xs font-bold rounded-[5px] border border-[#E8DFC9] bg-white text-[#142010] focus:outline-none focus:border-[#2A7C13]"
            >
              {allStreams.map((s) => (
                <option key={s.id} value={s.id}>
                  {s.name}
                </option>
              ))}
            </select>
          </div>
        )}
      </div>

      {/* Notification Toast */}
      {message && (
        <div
          className={`p-3 rounded-[6px] text-xs flex items-center justify-between gap-2 ${
            message.type === "success"
              ? "bg-[#EAF7E4] text-[#2A7C13] border border-[#76C457]/40"
              : "bg-red-50 text-red-700 border border-red-200"
          }`}
        >
          <div className="flex items-center gap-2">
            {message.type === "success" ? (
              <CheckCircle2 className="w-4 h-4 shrink-0" />
            ) : (
              <AlertCircle className="w-4 h-4 shrink-0" />
            )}
            <span>{message.text}</span>
          </div>
          <button type="button" onClick={() => setMessage(null)} className="text-current opacity-70 hover:opacity-100">
            <X className="w-3.5 h-3.5" />
          </button>
        </div>
      )}

      {/* ══════════════════════════════════════════════════════════════════ */}
      {/* ── TAB 1: LIVE WEEKLY CLASS TIMETABLE MATRIX ───────────────────── */}
      {/* ══════════════════════════════════════════════════════════════════ */}
      {activeTab === "grid" && (
        <div className="space-y-4">
          {/* Active Profile Info Banner */}
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 p-3.5 rounded-[8px] bg-[#FFFDF5] border border-[#E8DFC9]">
            <div className="flex items-center gap-2.5">
              <div className="w-8 h-8 rounded-full bg-[#EAF7E4] text-[#2A7C13] flex items-center justify-center font-bold text-xs">
                {activeStream?.name?.slice(0, 2).toUpperCase() || "CL"}
              </div>
              <div>
                <h2 className="text-xs font-bold text-[#142010]">
                  Weekly Timetable for {activeStream?.name || "Class"}
                </h2>
                <p className="text-[11px] text-[#525E4B]">
                  Schedule Bell Profile:{" "}
                  <strong className="text-[#2A7C13]">
                    {activeProfile?.name || "General Grammar Profile"}
                  </strong>{" "}
                  ({activeProfile?.default_period_duration_minutes || 50} mins / period)
                </p>
              </div>
            </div>

            <div className="flex items-center gap-2 text-[11px] text-[#525E4B]">
              <span className="inline-flex items-center gap-1 font-medium">
                <span className="w-2 h-2 rounded-full bg-[#2A7C13]"></span>
                <span>Active Periods: {activePeriods.filter((p) => !p.is_break).length}</span>
              </span>
              <span className="text-[#E8DFC9]">·</span>
              <span className="inline-flex items-center gap-1 font-medium">
                <span className="w-2 h-2 rounded-full bg-[#B45309]"></span>
                <span>Breaks: {activePeriods.filter((p) => p.is_break).length}</span>
              </span>
            </div>
          </div>

          {/* Matrix Grid */}
          {activePeriods.length === 0 ? (
            <div className="p-8 text-center bg-white rounded-[8px] border border-[#E8DFC9] space-y-3">
              <Clock className="w-8 h-8 text-[#B45309] mx-auto" />
              <h3 className="text-sm font-bold text-[#142010]">No Bell Schedule Periods Configured</h3>
              <p className="text-xs text-[#525E4B] max-w-md mx-auto">
                Configure your school start time, period durations, and breaks before scheduling classes.
              </p>
              {(isAdmin || isHod) && (
                <button
                  type="button"
                  onClick={() => setActiveTab("profiles")}
                  className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-[5px] bg-[#2A7C13] text-white text-xs font-bold"
                >
                  <Plus className="w-3.5 h-3.5" />
                  <span>Configure Bell Schedule</span>
                </button>
              )}
            </div>
          ) : (
            <div className="bg-white rounded-[8px] border border-[#E8DFC9] shadow-2xs overflow-hidden">
              <div className="overflow-x-auto">
                <table className="w-full min-w-[850px] border-collapse text-left text-xs">
                  <thead>
                    <tr className="bg-[#FFFDF5] border-b border-[#E8DFC9] text-[#525E4B] font-bold text-[11px]">
                      <th className="py-2.5 px-3 w-36 border-r border-[#E8DFC9]">Period / Time</th>
                      {DAYS_OF_WEEK.map((d) => (
                        <th key={d.day} className="py-2.5 px-3 border-r border-[#E8DFC9] last:border-r-0">
                          {d.name} <span className="text-[10px] text-[#788470]">({d.fr})</span>
                        </th>
                      ))}
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-[#F5EFE0]">
                    {activePeriods.map((period) => {
                      if (period.is_break) {
                        return (
                          <tr key={period.id} className="bg-[#FFF8CF]/40 text-[#7A4A00]">
                            <td className="py-2 px-3 font-semibold text-[11px] border-r border-[#E8DFC9]">
                              <span className="font-mono text-[10px] text-[#B45309] block">
                                {period.start_time.slice(0, 5)} – {period.end_time.slice(0, 5)}
                              </span>
                              <span>{period.name}</span>
                            </td>
                            <td
                              colSpan={5}
                              className="py-2 px-3 text-center text-xs font-bold uppercase tracking-wider text-[#92400E]"
                            >
                              ☕ {period.name} ({period.start_time.slice(0, 5)} – {period.end_time.slice(0, 5)})
                            </td>
                          </tr>
                        );
                      }

                      return (
                        <tr key={period.id} className="hover:bg-[#FFFDF5]/60 transition-colors">
                          {/* Period Title & Timing */}
                          <td className="py-2.5 px-3 border-r border-[#E8DFC9] bg-[#FFFDF5]/40">
                            <span className="font-bold text-[#142010] block text-xs">{period.name}</span>
                            <span className="font-mono text-[10.5px] text-[#525E4B]">
                              {period.start_time.slice(0, 5)} – {period.end_time.slice(0, 5)}
                            </span>
                          </td>

                          {/* Day Columns */}
                          {DAYS_OF_WEEK.map((d) => {
                            const slot = streamSlotsMap.get(`${d.day}-${period.id}`);
                            return (
                              <td
                                key={d.day}
                                onClick={() => handleOpenSlotModal(d.day, period)}
                                className={`py-1.5 px-2 border-r border-[#E8DFC9] last:border-r-0 align-top transition-colors ${
                                  isAdmin || isHod ? "cursor-pointer hover:bg-[#EAF7E4]/40" : ""
                                }`}
                              >
                                {slot ? (
                                  <div className="p-2 rounded-[5px] bg-[#F5EFE0]/60 border border-[#E8DFC9] hover:border-[#2A7C13] transition-colors space-y-1 group">
                                    <div className="flex items-start justify-between gap-1">
                                      <strong className="text-xs font-extrabold text-[#142010] line-clamp-1">
                                        {slot.subject?.name}
                                      </strong>
                                      <span className="px-1.5 py-0.2 rounded bg-white text-[9px] font-mono text-[#525E4B] border border-[#D5D5CF]">
                                        {slot.subject?.code || "SUB"}
                                      </span>
                                    </div>
                                    <div className="text-[10.5px] text-[#525E4B] flex items-center justify-between">
                                      <span className="truncate">{slot.teacher?.full_name || "Unassigned"}</span>
                                      {slot.room_name && (
                                        <span className="text-[9.5px] font-semibold text-[#2A7C13] shrink-0">
                                          📍 {slot.room_name}
                                        </span>
                                      )}
                                    </div>
                                  </div>
                                ) : (
                                  <div className="h-14 rounded-[4px] border border-dashed border-[#D5D5CF] flex items-center justify-center text-[10.5px] text-[#788470] opacity-50 hover:opacity-100">
                                    {isAdmin || isHod ? "+ Add Slot" : "Free"}
                                  </div>
                                )}
                              </td>
                            );
                          })}
                        </tr>
                      );
                    })}
                  </tbody>
                </table>
              </div>
            </div>
          )}
        </div>
      )}

      {/* ══════════════════════════════════════════════════════════════════ */}
      {/* ── TAB 2: BELL SCHEDULES & SUBSYSTEMS CONFIGURATION ────────────── */}
      {/* ══════════════════════════════════════════════════════════════════ */}
      {activeTab === "profiles" && (isAdmin || isHod) && (
        <div className="space-y-6">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3">
            <div>
              <h2 className="text-sm font-bold text-[#142010]">Timetable Profiles &amp; Bell Schedules</h2>
              <p className="text-xs text-[#525E4B]">
                Configure distinct timings for General Grammar, Technical Workshop blocks, and Commercial sections.
              </p>
            </div>
            <button
              type="button"
              onClick={() => setShowProfileModal(true)}
              className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-[5px] bg-[#2A7C13] text-white text-xs font-bold shadow-xs hover:bg-[#20600E] cursor-pointer"
            >
              <Plus className="w-3.5 h-3.5" />
              <span>New Timetable Profile</span>
            </button>
          </div>

          {/* Profile Cards */}
          <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
            {initialProfiles.map((p) => {
              const isSelected = p.id === activeProfile?.id;
              return (
                <div
                  key={p.id}
                  onClick={() => setSelectedProfileId(p.id)}
                  className={`p-4 rounded-[8px] border transition-all cursor-pointer ${
                    isSelected
                      ? "bg-white border-[#2A7C13] ring-1 ring-[#2A7C13] shadow-sm"
                      : "bg-[#FFFDF5] border-[#E8DFC9] hover:border-[#788470]"
                  }`}
                >
                  <div className="flex items-start justify-between gap-2">
                    <div>
                      <span className="px-2 py-0.5 rounded-[4px] bg-[#F5EFE0] text-[10px] uppercase font-bold text-[#525E4B]">
                        {p.subsystem}
                      </span>
                      <h3 className="text-sm font-extrabold text-[#142010] mt-1">{p.name}</h3>
                    </div>
                    {isSelected && <Check className="w-4 h-4 text-[#2A7C13]" />}
                  </div>

                  <div className="mt-3 pt-3 border-t border-[#F5EFE0] text-xs text-[#525E4B] space-y-1">
                    <p>
                      Start Time: <strong className="text-[#142010]">{p.day_start_time.slice(0, 5)}</strong>
                    </p>
                    <p>
                      Period Length: <strong className="text-[#142010]">{p.default_period_duration_minutes} mins</strong>
                    </p>
                    <p>
                      Configured Slots: <strong className="text-[#2A7C13]">{p.periods?.length || 0} periods</strong>
                    </p>
                  </div>
                </div>
              );
            })}
          </div>

          {/* Period Manager for Currently Selected Profile */}
          {activeProfile && (
            <div className="p-5 bg-white rounded-[8px] border border-[#E8DFC9] shadow-2xs space-y-4">
              <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-3 border-b border-[#F5EFE0]">
                <div>
                  <h3 className="text-xs font-bold uppercase tracking-wider text-[#788470]">
                    Bell Periods for: <strong className="text-[#142010]">{activeProfile.name}</strong>
                  </h3>
                  <p className="text-[11px] text-[#525E4B]">
                    Morning start: {activeProfile.day_start_time.slice(0, 5)} • {activeProfile.default_period_duration_minutes} minutes per period
                  </p>
                </div>

                <button
                  type="button"
                  onClick={() => {
                    setAutoStart(activeProfile.day_start_time.slice(0, 5));
                    setAutoDuration(activeProfile.default_period_duration_minutes);
                    setShowAutoPeriodsModal(true);
                  }}
                  className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-[5px] border border-[#2A7C13] bg-[#F0FDF4] text-[#166534] text-xs font-bold hover:bg-[#DCFCE7] cursor-pointer"
                >
                  <Sparkles className="w-3.5 h-3.5 text-[#2A7C13]" />
                  <span>Auto-Generate Periods &amp; Breaks</span>
                </button>
              </div>

              {/* Periods List Table */}
              <div className="overflow-x-auto text-xs">
                <table className="w-full text-left border-collapse">
                  <thead>
                    <tr className="border-b border-[#E8DFC9] text-[11px] font-bold text-[#525E4B]">
                      <th className="py-2 px-2 w-16 text-center">#</th>
                      <th className="py-2 px-3">Period Name</th>
                      <th className="py-2 px-3 w-32">Start Time</th>
                      <th className="py-2 px-3 w-32">End Time</th>
                      <th className="py-2 px-3 w-28">Type</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-[#F5EFE0]">
                    {activePeriods.map((p) => (
                      <tr key={p.id} className={p.is_break ? "bg-[#FFF8CF]/30" : ""}>
                        <td className="py-2 px-2 text-center font-bold text-[#525E4B]">{p.period_number}</td>
                        <td className="py-2 px-3 font-semibold text-[#142010]">{p.name}</td>
                        <td className="py-2 px-3 font-mono">{p.start_time.slice(0, 5)}</td>
                        <td className="py-2 px-3 font-mono">{p.end_time.slice(0, 5)}</td>
                        <td className="py-2 px-3">
                          {p.is_break ? (
                            <span className="px-2 py-0.5 rounded bg-[#FFF8CF] text-[#92400E] text-[10px] font-bold">
                              Break
                            </span>
                          ) : (
                            <span className="px-2 py-0.5 rounded bg-[#EAF7E4] text-[#2A7C13] text-[10px] font-bold">
                              Lesson
                            </span>
                          )}
                        </td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>
            </div>
          )}
        </div>
      )}

      {/* ══════════════════════════════════════════════════════════════════ */}
      {/* ── TAB 3: TEACHER FREE DAYS & VACATAIRE AVAILABILITY ───────────── */}
      {/* ══════════════════════════════════════════════════════════════════ */}
      {activeTab === "teachers" && (isAdmin || isHod) && (
        <div className="space-y-4">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 p-4 rounded-[8px] bg-white border border-[#E8DFC9]">
            <div>
              <h2 className="text-sm font-bold text-[#142010]">Part-Time &amp; Teacher Free Days</h2>
              <p className="text-xs text-[#525E4B]">
                Configure when part-time teachers are available to prevent scheduling them when they teach in other colleges.
              </p>
            </div>

            <div className="flex items-center gap-2">
              <span className="text-xs font-semibold text-[#525E4B]">Select Teacher:</span>
              <select
                value={selectedTeacherId}
                onChange={(e) => setSelectedTeacherId(e.target.value)}
                className="px-3 py-1.5 text-xs font-bold rounded-[5px] border border-[#E8DFC9] bg-[#FFFDF5] text-[#142010] focus:outline-none focus:border-[#2A7C13]"
              >
                {teachers.map((t) => (
                  <option key={t.id} value={t.id}>
                    {t.full_name}
                  </option>
                ))}
              </select>
            </div>
          </div>

          {/* Days Availability Matrix */}
          <div className="grid grid-cols-1 sm:grid-cols-5 gap-3">
            {DAYS_OF_WEEK.map((d) => {
              const av = teacherAvailMap.get(d.day);
              const isAvail = av ? av.is_available : true;
              return (
                <div
                  key={d.day}
                  className={`p-4 rounded-[8px] border text-center space-y-3 transition-colors ${
                    isAvail
                      ? "bg-white border-[#E8DFC9]"
                      : "bg-[#FFF8CF]/30 border-[#FBE6C2]"
                  }`}
                >
                  <h3 className="font-bold text-xs uppercase tracking-wider text-[#142010]">{d.name}</h3>
                  <div className="text-[11px] font-semibold">
                    {isAvail ? (
                      <span className="text-[#2A7C13] flex items-center justify-center gap-1">
                        <Check className="w-3.5 h-3.5" /> Available for Classes
                      </span>
                    ) : (
                      <span className="text-[#B45309] flex items-center justify-center gap-1">
                        <X className="w-3.5 h-3.5" /> Off-Day / At Other School
                      </span>
                    )}
                  </div>

                  <button
                    type="button"
                    onClick={() => handleToggleTeacherDay(d.day, isAvail)}
                    className={`w-full py-1.5 rounded-[4px] text-xs font-bold transition-colors cursor-pointer ${
                      isAvail
                        ? "bg-[#F5EFE0] text-[#7A4A00] hover:bg-[#FBE6C2]"
                        : "bg-[#2A7C13] text-white hover:bg-[#20600E]"
                    }`}
                  >
                    {isAvail ? "Mark as Off-Day" : "Set Available"}
                  </button>
                </div>
              );
            })}
          </div>
        </div>
      )}

      {/* ══════════════════════════════════════════════════════════════════ */}
      {/* ── TAB 4: PRINT INSPECTION PACK ────────────────────────────────── */}
      {/* ══════════════════════════════════════════════════════════════════ */}
      {activeTab === "print" && (
        <div className="space-y-4">
          <div className="p-4 rounded-[8px] bg-white border border-[#E8DFC9] flex flex-col sm:flex-row sm:items-center justify-between gap-3">
            <div>
              <h2 className="text-sm font-bold text-[#142010]">Inspection-Ready Timetable Printouts</h2>
              <p className="text-xs text-[#525E4B]">
                Print official A4 class wall timetables, individual teacher schedules, and the school master matrix for MINESEC inspections.
              </p>
            </div>

            <button
              type="button"
              onClick={() => window.print()}
              className="inline-flex items-center gap-1.5 px-4 py-2 rounded-[5px] bg-[#2A7C13] hover:bg-[#20600E] text-white text-xs font-bold shadow-xs cursor-pointer"
            >
              <Printer className="w-4 h-4" />
              <span>Print A4 Timetable</span>
            </button>
          </div>

          {/* Printable Preview Sheet */}
          <div className="bg-white p-8 rounded-[8px] border border-[#E8DFC9] shadow-sm text-xs space-y-4">
            <div className="text-center border-b pb-3 space-y-1">
              <h3 className="font-extrabold text-sm uppercase tracking-wider text-[#142010]">
                {school?.name || "Nsei Sukul College"}
              </h3>
              <p className="text-[10px] text-[#525E4B]">
                OFFICIAL CLASS TIMETABLE — {activeStream?.name} ({academicYear?.name || "2026/2027"})
              </p>
            </div>

            <table className="w-full border-collapse border border-[#142010] text-[10px]">
              <thead>
                <tr className="bg-[#F5EFE0] text-[#142010] font-bold">
                  <th className="border border-[#142010] py-1.5 px-2">Time</th>
                  {DAYS_OF_WEEK.map((d) => (
                    <th key={d.day} className="border border-[#142010] py-1.5 px-2 text-center">
                      {d.name}
                    </th>
                  ))}
                </tr>
              </thead>
              <tbody>
                {activePeriods.map((period) => (
                  <tr key={period.id}>
                    <td className="border border-[#142010] py-1.5 px-2 font-mono">
                      {period.start_time.slice(0, 5)} - {period.end_time.slice(0, 5)}
                    </td>
                    {period.is_break ? (
                      <td colSpan={5} className="border border-[#142010] py-1 px-2 text-center font-bold bg-[#F5EFE0]">
                        {period.name}
                      </td>
                    ) : (
                      DAYS_OF_WEEK.map((d) => {
                        const slot = streamSlotsMap.get(`${d.day}-${period.id}`);
                        return (
                          <td key={d.day} className="border border-[#142010] py-1 px-1.5 text-center">
                            {slot ? (
                              <div>
                                <strong className="block text-[10px]">{slot.subject?.name}</strong>
                                <span className="text-[8.5px] text-[#525E4B]">
                                  {slot.teacher?.full_name?.split(" ")[0]} {slot.room_name ? `(${slot.room_name})` : ""}
                                </span>
                              </div>
                            ) : (
                              <span className="text-[#999]">—</span>
                            )}
                          </td>
                        );
                      })
                    )}
                  </tr>
                ))}
              </tbody>
            </table>
          </div>
        </div>
      )}

      {/* ── MODAL: ASSIGN TIMETABLE SLOT ── */}
      {activeSlotModal && (
        <div className="fixed inset-0 z-50 bg-[#142010]/60 backdrop-blur-xs flex items-center justify-center p-4">
          <div className="bg-white rounded-[8px] border border-[#E8DFC9] shadow-xl max-w-md w-full p-5 space-y-4">
            <div className="flex items-start justify-between border-b pb-3">
              <div>
                <h3 className="font-extrabold text-sm text-[#142010]">
                  Schedule: {DAYS_OF_WEEK.find((d) => d.day === activeSlotModal.dayOfWeek)?.name} ({activeSlotModal.period.name})
                </h3>
                <p className="text-[11px] text-[#525E4B]">
                  {activeStream?.name} • {activeSlotModal.period.start_time.slice(0, 5)} – {activeSlotModal.period.end_time.slice(0, 5)}
                </p>
              </div>
              <button
                type="button"
                onClick={() => setActiveSlotModal(null)}
                className="text-[#788470] hover:text-[#142010]"
              >
                <X className="w-4 h-4" />
              </button>
            </div>

            <form onSubmit={handleSaveSlot} className="space-y-3 text-xs">
              <div>
                <label className="block text-[11px] font-bold text-[#525E4B] mb-1">Subject</label>
                <select
                  value={slotSubjectId}
                  onChange={(e) => setSlotSubjectId(e.target.value)}
                  className="w-full px-3 py-1.5 rounded-[5px] border border-[#E8DFC9] bg-[#FFFDF5] font-semibold text-[#142010]"
                >
                  {subjects.map((s) => (
                    <option key={s.id} value={s.id}>
                      {s.name} ({s.code})
                    </option>
                  ))}
                </select>
              </div>

              <div>
                <label className="block text-[11px] font-bold text-[#525E4B] mb-1">Teacher</label>
                <select
                  value={slotTeacherId}
                  onChange={(e) => setSlotTeacherId(e.target.value)}
                  className="w-full px-3 py-1.5 rounded-[5px] border border-[#E8DFC9] bg-[#FFFDF5] font-semibold text-[#142010]"
                >
                  <option value="">No teacher assigned</option>
                  {teachers.map((t) => (
                    <option key={t.id} value={t.id}>
                      {t.full_name}
                    </option>
                  ))}
                </select>
              </div>

              <div>
                <label className="block text-[11px] font-bold text-[#525E4B] mb-1">Room / Workshop (Optional)</label>
                <input
                  type="text"
                  value={slotRoomName}
                  onChange={(e) => setSlotRoomName(e.target.value)}
                  placeholder="e.g. Computer Lab, Physics Lab, Hall B"
                  className="w-full px-3 py-1.5 rounded-[5px] border border-[#E8DFC9] bg-white font-medium text-[#142010]"
                />
              </div>

              <div className="flex items-center justify-between pt-3 border-t">
                {activeSlotModal.existingSlot ? (
                  <button
                    type="button"
                    onClick={() => handleDeleteSlot(activeSlotModal.existingSlot!.id)}
                    className="inline-flex items-center gap-1 text-red-600 hover:text-red-700 text-xs font-semibold cursor-pointer"
                  >
                    <Trash2 className="w-3.5 h-3.5" />
                    <span>Clear Slot</span>
                  </button>
                ) : (
                  <div></div>
                )}

                <div className="flex items-center gap-2">
                  <button
                    type="button"
                    onClick={() => setActiveSlotModal(null)}
                    className="px-3 py-1.5 rounded-[5px] border border-[#E8DFC9] text-xs font-semibold text-[#525E4B]"
                  >
                    Cancel
                  </button>
                  <button
                    type="submit"
                    disabled={isPending}
                    className="px-4 py-1.5 rounded-[5px] bg-[#2A7C13] hover:bg-[#20600E] text-white text-xs font-bold shadow-xs cursor-pointer"
                  >
                    {isPending ? "Checking & Saving..." : "Save Slot"}
                  </button>
                </div>
              </div>
            </form>
          </div>
        </div>
      )}

      {/* ── MODAL: NEW TIMETABLE PROFILE ── */}
      {showProfileModal && (
        <div className="fixed inset-0 z-50 bg-[#142010]/60 backdrop-blur-xs flex items-center justify-center p-4">
          <div className="bg-white rounded-[8px] border border-[#E8DFC9] shadow-xl max-w-md w-full p-5 space-y-4">
            <div className="flex items-start justify-between border-b pb-3">
              <div>
                <h3 className="font-extrabold text-sm text-[#142010]">New Timetable Profile</h3>
                <p className="text-[11px] text-[#525E4B]">Create a schedule profile for your educational section.</p>
              </div>
              <button type="button" onClick={() => setShowProfileModal(false)}>
                <X className="w-4 h-4 text-[#788470]" />
              </button>
            </div>

            <form onSubmit={handleCreateProfile} className="space-y-3 text-xs">
              <div>
                <label className="block text-[11px] font-bold text-[#525E4B] mb-1">Profile Name</label>
                <input
                  type="text"
                  required
                  value={profileName}
                  onChange={(e) => setProfileName(e.target.value)}
                  placeholder="e.g. Technical & Industrial Workshop Schedule"
                  className="w-full px-3 py-1.5 rounded-[5px] border border-[#E8DFC9]"
                />
              </div>

              <div>
                <label className="block text-[11px] font-bold text-[#525E4B] mb-1">Subsystem</label>
                <select
                  value={profileSubsystem}
                  onChange={(e) => setProfileSubsystem(e.target.value as any)}
                  className="w-full px-3 py-1.5 rounded-[5px] border border-[#E8DFC9] bg-[#FFFDF5]"
                >
                  <option value="grammar">General Grammar</option>
                  <option value="technical">Technical &amp; Industrial</option>
                  <option value="commercial">Commercial Section</option>
                  <option value="general">General Comprehensive</option>
                </select>
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block text-[11px] font-bold text-[#525E4B] mb-1">Start Time</label>
                  <input
                    type="time"
                    value={profileStartTime}
                    onChange={(e) => setProfileStartTime(e.target.value)}
                    className="w-full px-3 py-1.5 rounded-[5px] border border-[#E8DFC9]"
                  />
                </div>
                <div>
                  <label className="block text-[11px] font-bold text-[#525E4B] mb-1">Period Length (mins)</label>
                  <input
                    type="number"
                    min={30}
                    max={120}
                    value={profileDuration}
                    onChange={(e) => setProfileDuration(Number(e.target.value))}
                    className="w-full px-3 py-1.5 rounded-[5px] border border-[#E8DFC9]"
                  />
                </div>
              </div>

              <div className="flex items-center justify-end gap-2 pt-3 border-t">
                <button
                  type="button"
                  onClick={() => setShowProfileModal(false)}
                  className="px-3 py-1.5 rounded-[5px] border text-xs font-semibold"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  disabled={isPending}
                  className="px-4 py-1.5 rounded-[5px] bg-[#2A7C13] text-white text-xs font-bold"
                >
                  {isPending ? "Creating..." : "Create Profile"}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}

      {/* ── MODAL: AUTO-GENERATE PERIODS ── */}
      {showAutoPeriodsModal && (
        <div className="fixed inset-0 z-50 bg-[#142010]/60 backdrop-blur-xs flex items-center justify-center p-4">
          <div className="bg-white rounded-[8px] border border-[#E8DFC9] shadow-xl max-w-md w-full p-5 space-y-4">
            <div className="flex items-start justify-between border-b pb-3">
              <div>
                <h3 className="font-extrabold text-sm text-[#142010]">Auto-Generate Bell Schedule</h3>
                <p className="text-[11px] text-[#525E4B]">
                  Instantly compute morning lessons, assembly, short break, and lunch break.
                </p>
              </div>
              <button type="button" onClick={() => setShowAutoPeriodsModal(false)}>
                <X className="w-4 h-4 text-[#788470]" />
              </button>
            </div>

            <form onSubmit={handleAutoGeneratePeriods} className="space-y-3 text-xs">
              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block text-[11px] font-bold text-[#525E4B] mb-1">Day Start Time</label>
                  <input
                    type="time"
                    value={autoStart}
                    onChange={(e) => setAutoStart(e.target.value)}
                    className="w-full px-3 py-1.5 rounded-[5px] border"
                  />
                </div>
                <div>
                  <label className="block text-[11px] font-bold text-[#525E4B] mb-1">Period Length (mins)</label>
                  <input
                    type="number"
                    value={autoDuration}
                    onChange={(e) => setAutoDuration(Number(e.target.value))}
                    className="w-full px-3 py-1.5 rounded-[5px] border"
                  />
                </div>
              </div>

              <div>
                <label className="block text-[11px] font-bold text-[#525E4B] mb-1">Total Lesson Periods per Day</label>
                <input
                  type="number"
                  min={5}
                  max={10}
                  value={autoCount}
                  onChange={(e) => setAutoCount(Number(e.target.value))}
                  className="w-full px-3 py-1.5 rounded-[5px] border"
                />
              </div>

              <div className="grid grid-cols-2 gap-3 pt-2 border-t">
                <div>
                  <label className="block text-[11px] font-bold text-[#525E4B] mb-1">Short Break After Period</label>
                  <input
                    type="number"
                    value={autoShortBreakPeriod}
                    onChange={(e) => setAutoShortBreakPeriod(Number(e.target.value))}
                    className="w-full px-3 py-1.5 rounded-[5px] border"
                  />
                </div>
                <div>
                  <label className="block text-[11px] font-bold text-[#525E4B] mb-1">Short Break (mins)</label>
                  <input
                    type="number"
                    value={autoShortBreakDuration}
                    onChange={(e) => setAutoShortBreakDuration(Number(e.target.value))}
                    className="w-full px-3 py-1.5 rounded-[5px] border"
                  />
                </div>
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block text-[11px] font-bold text-[#525E4B] mb-1">Lunch Break After Period</label>
                  <input
                    type="number"
                    value={autoLunchPeriod}
                    onChange={(e) => setAutoLunchPeriod(Number(e.target.value))}
                    className="w-full px-3 py-1.5 rounded-[5px] border"
                  />
                </div>
                <div>
                  <label className="block text-[11px] font-bold text-[#525E4B] mb-1">Lunch Break (mins)</label>
                  <input
                    type="number"
                    value={autoLunchDuration}
                    onChange={(e) => setAutoLunchDuration(Number(e.target.value))}
                    className="w-full px-3 py-1.5 rounded-[5px] border"
                  />
                </div>
              </div>

              <div className="flex items-center justify-end gap-2 pt-3 border-t">
                <button
                  type="button"
                  onClick={() => setShowAutoPeriodsModal(false)}
                  className="px-3 py-1.5 rounded-[5px] border text-xs font-semibold"
                >
                  Cancel
                </button>
                <button
                  type="submit"
                  disabled={isPending}
                  className="px-4 py-1.5 rounded-[5px] bg-[#2A7C13] text-white text-xs font-bold"
                >
                  {isPending ? "Generating..." : "Generate Schedule"}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
}
